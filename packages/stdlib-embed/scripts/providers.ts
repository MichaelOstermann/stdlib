// Builds src/OEmbed/providers.ts from the provider list of oembed.com. Usage: bun scripts/providers.ts
import { execFileSync } from "node:child_process"
import { mkdtempSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"

const commit = "9e1720b12248d06cb9cac31e9b2b81f64669713b"

const root = join(import.meta.dir, "..")

type Source = {
    endpoints: { formats?: string[], schemes?: string[], url: string }[]
    provider_name: string
    provider_url: string
}

const response = await fetch(`https://codeload.github.com/iamcal/oembed/tar.gz/${commit}`)
if (!response.ok) throw new Error(`${response.status} ${response.url}`)

const dir = mkdtempSync(join(tmpdir(), "oembed-"))
writeFileSync(join(dir, "oembed.tgz"), Buffer.from(await response.arrayBuffer()))
execFileSync("tar", ["-xzf", "oembed.tgz", "--strip-components=1"], { cwd: dir })

const sources = readdirSync(join(dir, "providers"))
    .filter((file) => file.endsWith(".yml"))
    .flatMap((file) => Bun.YAML.parse(readFileSync(join(dir, "providers", file), "utf8")) as Source[])

const providers = sources
    .flatMap((source) => source.endpoints.map((endpoint) => ({
        endpoint: endpoint.url.replace("{format}", "json"),
        formats: endpoint.formats,
        name: source.provider_name,
        schemes: endpoint.schemes ?? [],
        url: source.provider_url,
    })))
    .filter((provider) => provider.schemes.length > 0)
    .filter((provider) => !provider.formats || provider.formats.includes("json"))
    .map(({ formats: _, ...provider }) => provider)
    .toSorted((a, b) => a.name.localeCompare(b.name))

writeFileSync(
    join(root, "src/OEmbed/providers.ts"),
    `// Generated by scripts/providers.ts from iamcal/oembed@${commit.slice(0, 7)}, MIT License, Copyright (c) 2016 Cal Henderson.
import type { OEmbedProvider } from "."

/**
 * # providers
 *
 * \`\`\`ts
 * const OEmbed.providers: OEmbedProvider[]
 * \`\`\`
 *
 * The providers listed on [oembed.com](https://oembed.com), by name.
 */
export const providers: OEmbedProvider[] = ${JSON.stringify(providers, null, 4)}
`,
)

execFileSync("bunx", ["dprint", "fmt", "src/OEmbed/providers.ts"], { cwd: root, stdio: "inherit" })

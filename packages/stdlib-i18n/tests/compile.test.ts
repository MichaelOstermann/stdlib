import { mkdtemp, rm } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { stdlibBun } from "@monstermann/stdlib-transform"
import { $ } from "bun"
import { afterEach, describe, expect, it } from "bun:test"
import { compile } from "../src/compile"

let root: string | undefined

afterEach(async () => {
    if (root) await rm(root, { force: true, recursive: true })
    root = undefined
})

/** A repository with these files. */
async function repo(files: Record<string, string>): Promise<string> {
    root = await mkdtemp(join(tmpdir(), "stdlib-i18n-"))
    for (const [path, contents] of Object.entries(files)) await Bun.write(join(root, path), contents)
    await $`git init -q`.cwd(root)
    return root
}

const bin = join(import.meta.dir, "../../../node_modules/.bin")
const options = { messages: ["i18n/*.yaml"], output: "app/i18n" }

const auth = `
auth.signIn:
  en: Sign in
  de: Anmelden

auth.sent:
  en: We sent a code to {email}
  de: Wir haben einen Code an {email} gesendet
`

describe("compile", () => {
    it("should write the types, m and every message, named after its key", async () => {
        const root = await repo({ "i18n/auth.yaml": auth })
        const result = await compile(options, root)
        expect(result).toEqual({ errors: [], output: { messages: 2, path: "app/i18n", written: true }, warnings: [] })
        expect(await Bun.file(join(root, "app/i18n/index.ts")).text()).toBe(`// Generated by stdlib-i18n, do not edit.
// dprint-ignore-file

import * as messages from "./_messages"

export const langs = ["de", "en"] as const

export type Lang = typeof langs[number]

export type MessageContext = { lang: Lang }

export const m = {
    auth: {
        sent: messages._authSent,
        signIn: messages._authSignIn,
    },
}
`)
        expect(await Bun.file(join(root, "app/i18n/_messages.ts")).text()).toBe(`// Generated by stdlib-i18n, do not edit.
// dprint-ignore-file

import type { MessageContext } from "./index"

export function _authSent(ctx: MessageContext, props: { email: number | string }): string {
    if (ctx.lang === "de") return \`Wir haben einen Code an \${props.email} gesendet\`
    return \`We sent a code to \${props.email}\`
}

export function _authSignIn(ctx: MessageContext): string {
    if (ctx.lang === "de") return "Anmelden"
    return "Sign in"
}
`)
        // The same files again.
        expect((await compile(options, root)).output!.written).toBe(false)
    })

    it("should nest groups", async () => {
        const root = await repo({ "i18n/all.yaml": "a.b.c:\n  en: C\na.d:\n  en: D\nfrom:\n  en: From\n" })
        await compile(options, root)
        expect(await Bun.file(join(root, "app/i18n/_messages.ts")).text()).toContain("export function _from(_ctx: MessageContext): string {")
        expect(await Bun.file(join(root, "app/i18n/index.ts")).text()).toEndWith(`export const m = {
    a: {
        b: {
            c: messages._aBC,
        },
        d: messages._aD,
    },
    from: messages._from,
}
`)
        const { m } = await import(join(root, "app/i18n/index.ts"))
        expect(m.a.b.c({ lang: "en" })).toBe("C")
        expect(m.from({ lang: "en" })).toBe("From")
    })

    it("should report keys that do not make names", async () => {
        const root = await repo({
            "i18n/all.yaml": `
auth.sign-in:
  en: Sign in
auth.signIn:
  en: Sign in
authSign.in:
  en: Sign in
auth:
  en: Auth
1st:
  en: First
`,
        })
        const result = await compile(options, root)
        expect(result.errors).toEqual([
            { line: 2, message: `auth.sign-in: "sign-in" is not an identifier, rename to "signIn"`, path: "i18n/all.yaml" },
            { line: 6, message: "authSign.in: conflicts with auth.signIn", path: "i18n/all.yaml" },
            { line: 8, message: "auth: conflicts with auth.signIn", path: "i18n/all.yaml" },
            { line: 10, message: `1st: "1st" is not an identifier`, path: "i18n/all.yaml" },
        ])
        expect(result.output).toBeUndefined()
    })

    it("should read the files of every glob", async () => {
        const root = await repo({
            "app/i18n/auth.yaml": auth,
            "server/mail/mail.yaml": "mail.subject:\n  en: Your code\n  de: Dein Code\n",
        })
        const result = await compile({ messages: ["./app/i18n/*.yaml", "server/mail/mail.yaml"], output: "shared/i18n" }, root)
        expect(result.output).toEqual({ messages: 3, path: "shared/i18n", written: true })
        expect(await Bun.file(join(root, "shared/i18n/_messages.ts")).text()).toContain("export function _mailSubject(")
    })

    it("should not read ignored files", async () => {
        const root = await repo({
            ".gitignore": "old",
            "i18n/auth.yaml": auth,
            "i18n/old/broken.yaml": "a: [b",
        })
        expect((await compile({ messages: ["i18n/**/*.yaml"], output: "app/i18n" }, root)).errors).toEqual([])
    })

    it("should warn about what the output works with, and still write it", async () => {
        const root = await repo({
            "i18n/auth.yaml": auth,
            "i18n/other.yaml": `
auth.signIn:
  en: Again
  de: Nochmal
nested:
  group:
    en: Nested
onlyEn:
  en: "{count, number} new"
`,
        })
        const result = await compile(options, root)
        expect(result).toEqual({
            errors: [],
            output: { messages: 3, path: "app/i18n", written: true },
            warnings: [
                { line: 2, message: "auth.signIn: already in i18n/auth.yaml:2", path: "i18n/other.yaml" },
                { line: 5, message: "nested: expected one message per language", path: "i18n/other.yaml" },
                { line: 8, message: `onlyEn: missing "de"`, path: "i18n/other.yaml" },
            ],
        })
        const { m } = await import(join(root, "app/i18n/index.ts"))
        expect(m.auth.signIn({ lang: "de" })).toBe("Anmelden")
        // English, with English numbers.
        expect(m.onlyEn({ lang: "de" }, { count: 1200 })).toBe("1,200 new")
    })

    it("should point at the line of a key, quoted or not, and of its language", async () => {
        const root = await repo({
            "i18n/all.yaml": `# Comment
"a" :
  en: A
  de: A
'b.c': { en: B }
d.e:   # Comment
  # en: Old
  de: D
  en: "{x"
`,
        })
        const result = await compile(options, root)
        expect(result.errors).toEqual([{ line: 9, message: `d.e (en): expected "}" or "," after "{x"`, path: "i18n/all.yaml" }])
        expect(result.warnings).toEqual([{ line: 5, message: `b.c: missing "de"`, path: "i18n/all.yaml" }])
    })

    it("should report what would break the output, and write nothing", async () => {
        const root = await repo({
            "i18n/auth.yaml": auth,
            "i18n/invalid.yaml": `a: [b`,
            "i18n/broken.yaml": `
syntax:
  en: "{broken"
  de: Kaputt
other:
  en: "{count, plural, one {# item}}"
  de: "{count, plural, one {# Ding}}"
`,
            "i18n/style.yaml": `
style:
  en: "{when, date, weird}"
`,
        })
        const result = await compile(options, root)
        expect(result.errors).toEqual([
            { line: 3, message: `syntax (en): expected "}" or "," after "{broken"`, path: "i18n/broken.yaml" },
            { line: 6, message: `other (en): missing "other" after "…nt, plural, one {# item}"`, path: "i18n/broken.yaml" },
            { line: 7, message: `other (de): missing "other" after "…nt, plural, one {# Ding}"`, path: "i18n/broken.yaml" },
            { message: "invalid YAML: Unexpected token", path: "i18n/invalid.yaml" },
            { line: 3, message: `style (en): unknown style "weird", expected short, medium, long, full after "{when, date, "`, path: "i18n/style.yaml" },
        ])
        expect(result.output).toBeUndefined()
        expect(await Bun.file(join(root, "app/i18n/index.ts")).exists()).toBe(false)
    })

    it("should compile numbers, dates, selects and plurals", async () => {
        const root = await repo({
            // `a` \ ${x} {name}, in a template literal, where ICU quotes braces with apostrophes.
            "i18n/quote.yaml": "quote:\n  en: \"`a` \\\\ $'{'x'}' {name}\"\n",
            "i18n/all.yaml": `
count:
  en: "{name} has {count, plural, =0 {no items} one {# item} other {# items}} since {when, date, short}"
  de: "{name} hat {count, plural, =0 {nichts} other {# Dinge}} seit {when, date, short}"
left:
  en: "{count, plural, one {# left} other {# left}}"
  pt-BR: "{count, plural, one {# restante} other {# restantes}}"
role:
  en: "{role, select, admin {Admin} other {Member}}"
`,
        })
        const result = await compile(options, root)
        expect(result.errors).toEqual([])
        const code = await Bun.file(join(root, "app/i18n/_messages.ts")).text()
        expect(code).toContain(`(ctx: MessageContext, props: { count: number, name: number | string, when: Date | number })`)
        // Only the helpers it calls.
        expect(code).toContain("const dateFormat = ")
        expect(code).not.toContain("timeFormat")

        const { m } = await import(join(root, "app/i18n/index.ts"))
        const when = new Date(2026, 9, 27)
        expect(m.count({ lang: "en" }, { count: 0, name: "Ada", when })).toBe("Ada has no items since 10/27/26")
        expect(m.count({ lang: "en" }, { count: 1, name: "Ada", when })).toBe("Ada has 1 item since 10/27/26")
        expect(m.count({ lang: "de" }, { count: 1200, name: "Ada", when })).toBe("Ada hat 1.200 Dinge seit 27.10.26")
        // English for a language that has not been translated yet.
        expect(m.count({ lang: "pt-BR" }, { count: 2, name: "Ada", when })).toBe("Ada has 2 items since 10/27/26")
        expect(m.left({ lang: "pt-BR" }, { count: 1200 })).toBe("1.200 restantes")
        expect(m.left({ lang: "de" }, { count: 1200 })).toBe("1,200 left")
        expect(m.role({ lang: "en" }, { role: "admin" })).toBe("Admin")
        expect(m.role({ lang: "de" }, { role: "guest" })).toBe("Member")
        expect(m.quote({ lang: "en" }, { name: "Ada" })).toBe(`\`a\` \\ $\{x} Ada`)
    })

    it("should type the key and the props of every message", async () => {
        const root = await repo({
            "i18n/auth.yaml": auth,
            "tsconfig.json": JSON.stringify({ compilerOptions: { lib: ["ESNext"], module: "Preserve", noEmit: true, strict: true, target: "ESNext", verbatimModuleSyntax: true }, include: ["app"] }),
            "app/page.ts": `
import { m } from "./i18n"

m.auth.signIn({ lang: "de" })
m.auth.sent({ lang: "de" }, { email: "ada@example.com" })

// @ts-expect-error unknown key
m.auth.singIn({ lang: "de" })
// @ts-expect-error unknown language
m.auth.signIn({ lang: "fr" })
// @ts-expect-error missing props
m.auth.sent({ lang: "de" })
// @ts-expect-error wrong props
m.auth.sent({ lang: "de" }, { mail: "ada@example.com" })
`,
        })
        await compile(options, root)
        const tsc = await $`${join(bin, "tsc")} -p ${root}`.nothrow().quiet()
        expect(tsc.stdout.toString()).toBe("")
        expect(tsc.exitCode).toBe(0)
    })

    it("should bundle only the messages that are used, through stdlib-transform", async () => {
        const root = await repo({
            "app/entry.ts": `import { m } from "./i18n"\nexport const title = m.auth.signIn({ lang: "de" })\n`,
            "app/group.ts": `import { m } from "./i18n"\nexport const auth = m.auth\n`,
            "i18n/auth.yaml": auth,
        })
        await compile(options, root)
        const build = await Bun.build({ entrypoints: [join(root, "app/entry.ts")], minify: true, plugins: [stdlibBun()], target: "browser" })
        const code = await build.outputs[0]!.text()
        expect(code).toContain("Anmelden")
        expect(code).not.toContain("gesendet")
        // A group would bundle all of its messages.
        await expect(Bun.build({ entrypoints: [join(root, "app/group.ts")], plugins: [stdlibBun()], throw: true })).rejects.toThrow()
    })

    it("should write files oxlint finds nothing in", async () => {
        const root = await repo({
            "i18n/all.yaml": `
count:
  en: "{count, plural, one {# item} other {# items}} since {when, date, short}"
  de: "{count, plural, one {# Ding} other {# Dinge}} seit {when, time}"
only:
  en: Only English
`,
        })
        await compile(options, root)
        const config = join(import.meta.dir, "../../../oxlint.config.ts")
        const lint = await $`${join(bin, "oxlint")} -c ${config} ${join(root, "app/i18n/index.ts")} ${join(root, "app/i18n/_messages.ts")}`.nothrow().quiet()
        expect(lint.stdout.toString()).toBe("")
        expect(lint.exitCode).toBe(0)
    })
})

import { mkdir, readdir } from "node:fs/promises"
import Path from "node:path"

/**
 * Collects what `@monstermann/stdlib` makes available on globals, a file of `src/Array` is a function on `Array`, and writes:
 *
 * - `stdlib/src/declarations.ts`, the types
 * - `stdlib/src/patch.ts`, which defines them for real
 * - `stdlib-transform/src/globals.manifest.ts`, what the transformer replaces
 */
const interfaces: Record<string, string> = {
    Array: "ArrayConstructor",
    Function: "FunctionConstructor",
    JSON: "JSON",
    Map: "MapConstructor",
    Math: "Math",
    Number: "NumberConstructor",
    Object: "ObjectConstructor",
    Promise: "PromiseConstructor",
    Set: "SetConstructor",
    String: "StringConstructor",
}

/** Globals that are values themselves, and the file each one lives in. */
const values: Record<string, string> = {
    Action: "Action",
    AsyncEmitter: "Emitter",
    batch: "batch",
    Bytes: "Bytes/index",
    Duration: "Duration/index",
    Effect: "Effect",
    Emitter: "Emitter",
    Err: "Result",
    ErrAsync: "ResultAsync",
    match: "match",
    Memo: "Memo",
    Ok: "Result",
    OkAsync: "ResultAsync",
    peek: "peek",
    pipe: "pipe",
    Result: "Result",
    ResultAsync: "ResultAsync",
    Retry: "Retry/index",
    Semaphore: "Semaphore",
    SemaphoreFullError: "Semaphore",
    Signal: "Signal",
    Timer: "Timer/index",
}

/** The types that go with them: the file, and the parameters when there are any. */
const types: Record<string, [file: string, parameters?: string]> = {
    AsyncEmitter: ["Emitter", "T = void"],
    Effect: ["Effect"],
    Emitter: ["Emitter", "T = void"],
    Err: ["Result", "E, T = never"],
    Memo: ["Memo", "T = any"],
    Ok: ["Result", "T, E = never"],
    ReadonlySignal: ["Signal", "T = any"],
    Result: ["Result", "T, E"],
    ResultAsync: ["ResultAsync", "T, E"],
    RetryAgain: ["Retry/index", "E"],
    Semaphore: ["Semaphore"],
    SemaphoreFullError: ["Semaphore"],
    Signal: ["Signal", "T = any"],
}

/** Globals of their own that are objects of functions, each a file of the same name. */
const namespaces = ["Bytes", "Duration", "Retry", "Timer"]

const root = Path.resolve(import.meta.dirname, "..")
const src = Path.join(root, "packages/stdlib/src")
const header = "// Generated by scripts/globals.ts\n"
const globals: Record<string, string[]> = {}

for (const global of Object.keys(interfaces)) {
    const files = await readdir(Path.join(src, global)).catch(() => [])
    const names = files.filter(isFunction).map(file => file.slice(0, -3)).sort()
    if (names.length) globals[global] = names
}

const entries = Object.entries(globals)
const members: Record<string, string[]> = { ...globals }

for (const namespace of namespaces) {
    const files = await readdir(Path.join(src, namespace)).catch(() => [])
    members[namespace] = files.filter(isFunction).map(file => file.slice(0, -3)).sort()
}

function imports(type: string): string {
    return entries
        .flatMap(([global, names]) => names.map(name => `import ${type}{ ${name} as ${global}_${name} } from "./${global}/${name}"`))
        .join("\n")
}

await write("packages/stdlib/src/declarations.ts", `${header}
${imports("type ")}

// Properties instead of methods: a method of the same name as a native one silently becomes an overload of it.
declare global {
${entries.map(([global, names]) => `    interface ${interfaces[global]} {\n${names.map(name => `        ${name}: typeof ${global}_${name}`).join("\n")}\n    }`).join("\n\n")}

${Object.entries(values).map(([name, file]) => `    const ${name}: typeof import("./${file}").${name}`).join("\n")}

${(await Promise.all(Object.entries(types).map(async ([name, [file, parameters]]) => (await docOf(file, name)) + (parameters
    ? `    type ${name}<${parameters}> = import("./${file}").${name}<${parameters.replaceAll(/ = \w+/g, "")}>`
    : `    type ${name} = import("./${file}").${name}`)))).join("\n")}
}
`)

await write("packages/stdlib/src/patch.ts", `${header}/* eslint-disable */\n
import "./declarations"
import { define } from "./internals/define"
${imports("")}
${Object.entries(values).map(([name, file]) => `import { ${name} } from "./${file}"`).join("\n")}

${entries.map(([global, names]) => `define(${global}, "${global}", {\n${names.map(name => `    ${name}: ${global}_${name},`).join("\n")}\n})`).join("\n\n")}

define(globalThis, "globalThis", {
${Object.keys(values).map(name => `    ${name},`).join("\n")}
})

Object.defineProperty(globalThis, Symbol.for("@monstermann/stdlib/patch"), { configurable: true, value: true })
`)

await write("packages/stdlib-transform/src/globals.manifest.ts", `${header}
/** What @monstermann/stdlib makes available on globals, each is a file of the same name: \`Array.map\` → \`Array/map.mjs\`. */
export const globals: Readonly<Record<string, readonly string[]>> = {
${Object.entries(members).sort(([a], [b]) => a.localeCompare(b)).map(([global, names]) => `    ${global}: [${names.map(name => `"${name}"`).join(", ")}],`).join("\n")}
}

/** Globals that are values themselves, and the file each one lives in: \`pipe\` → \`pipe.mjs\`. */
export const values: Readonly<Record<string, string>> = {
${Object.entries(values).map(([name, file]) => `    ${name}: "${file}",`).join("\n")}
}
`)

/** The documentation of a type, an alias of it does not show it by itself. A barrel has its types next to it. */
async function docOf(file: string, name: string): Promise<string> {
    for (const path of [`${file}.ts`, Path.join(Path.dirname(file), "types.ts")]) {
        const code = await Bun.file(Path.join(src, path)).text().catch(() => "")
        const doc = code.match(new RegExp(`(/\\*\\*(?:(?!\\*/)[\\s\\S])*\\*/)\\n(?:export )?(?:type|class|interface) ${name}\\b`))?.[1]
        if (doc) return `    ${doc.replaceAll("\n", "\n    ")}\n`
    }
    return ""
}

/** A file that is something to call, named like it: not `index.ts`, `types.ts`, `a.d.ts` or `a.test.ts`. */
function isFunction(file: string): boolean {
    return /^[\w$]+\.ts$/.test(file) && file !== "index.ts" && file !== "types.ts"
}

/** Files are only written when their contents changed. */
async function write(file: string, contents: string): Promise<void> {
    const path = Path.join(root, file)
    if (await Bun.file(path).exists() && await Bun.file(path).text() === contents) return
    await mkdir(Path.dirname(path), { recursive: true })
    await Bun.write(path, contents)
    console.log(`Updated ${file}`)
}

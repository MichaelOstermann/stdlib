import { readdir } from "node:fs/promises"
import Path from "node:path"

/**
 * Collects the functions `@monstermann/stdlib` adds to the replicas of natives, a file of
 * `src/Array` is a function on `Array`, and writes them to
 * `stdlib-transform/src/replicas.manifest.ts`, what the transformer replaces.
 */
const replicas = ["Array", "Function", "JSON", "Map", "Math", "Object", "Promise", "Set", "String"]

const root = Path.resolve(import.meta.dirname, "..")
const src = Path.join(root, "packages/stdlib/src")
const file = "packages/stdlib-transform/src/replicas.manifest.ts"
const members: Record<string, string[]> = {}

for (const replica of replicas) {
    const files = await readdir(Path.join(src, replica))
    members[replica] = files.filter(isFunction).map((file) => file.slice(0, -3)).sort()
}

const contents = `// Generated by scripts/replicas.ts

/** The functions on each replica, each is a file of the same name: \`Array.map\` → \`Array/map\`. */
export const replicas: Readonly<Record<string, readonly string[]>> = {
${Object.entries(members).map(([replica, names]) => `    ${replica}: [${names.map((name) => `"${name}"`).join(", ")}],`).join("\n")}
}
`

const path = Path.join(root, file)
if (!await Bun.file(path).exists() || await Bun.file(path).text() !== contents) {
    await Bun.write(path, contents)
    console.log(`Updated ${file}`)
}

/**
 * A file that is something to call, named like it: not `index.ts`, `types.ts`, `a.d.ts` or
 * `a.test.ts`.
 */
function isFunction(file: string): boolean {
    return /^[\w$]+\.ts$/.test(file) && file !== "index.ts" && file !== "types.ts"
}
